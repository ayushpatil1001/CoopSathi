/**
 * Localizes a sector name
 */
export function getLocalizedSector(sector: string, langOrT?: LanguageCode | ((k: string, d?: string) => string)): string {
  if (!sector) return '';
  if (typeof langOrT === 'string') {
    if (langOrT === 'en') return sector;
    return SECTOR_TRANSLATIONS[sector]?.[langOrT] || sector;
  }
  // If a translate function is passed (backward-compat)
  return sector;
}

/**
 * Localizes a beneficiary label or tag
 */
export function getLocalizedBeneficiary(
  b: string,
  langOrDefault?: LanguageCode | string,
  t?: (k: string, d?: string) => string
): string {
  if (!b) return '';

  // If called as getLocalizedBeneficiary(tag, lang)
  if (langOrDefault && typeof langOrDefault === 'string' && ['en', 'hi', 'mr', 'gu', 'ta', 'te', 'bn'].includes(langOrDefault)) {
    const lang = langOrDefault as LanguageCode;
    if (lang === 'en') return b;
    return BENEFICIARY_TRANSLATIONS[b]?.[lang] || b;
  }

  // If called with filter ID and translation function t
  if (typeof t === 'function') {
    const key = BENEFICIARY_KEY_MAP[b];
    if (key) {
      return t(key, typeof langOrDefault === 'string' ? langOrDefault : b);
    }
  }

  return typeof langOrDefault === 'string' ? langOrDefault : b;
}

