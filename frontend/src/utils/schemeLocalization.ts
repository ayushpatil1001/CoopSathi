export function getLocalizedMinistry(ministry: string, lang: LanguageCode): string {
  if (!ministry) return '';
  if (lang === 'en') return ministry;
  return MINISTRY_TRANSLATIONS[ministry]?.[lang] || ministry;
}

/**
 * Returns localized scheme properties (title, benefitSummary, objective)
 * Grounded in schemesTranslations.json covering 100% of the 93 catalog schemes
 */
export function getLocalizedScheme(scheme: SchemeItem, lang: LanguageCode): LocalizedSchemeContent {
  if (lang === 'en') {
    return {
      title: scheme.title,
      benefitSummary: scheme.benefitSummary,
      objective: scheme.objective,
    };
  }

  const dict = schemesTranslationsData as Record<string, Record<string, { title: string; benefitSummary: string; objective: string }>>;
  const item = dict[scheme.id]?.[lang];

  if (item) {
    return {
      title: item.title || scheme.title,
      benefitSummary: item.benefitSummary || scheme.benefitSummary,
      objective: item.objective || scheme.objective,
    };
  }

  return {
    title: scheme.title,
    benefitSummary: scheme.benefitSummary,
    objective: scheme.objective,
  };
}
