import { ChatMessage, LanguageCode } from '../types';
import { apiService } from './apiService';

export class AIChatService {
  public async generateResponse(query: string, lang: LanguageCode = 'en'): Promise<ChatMessage> {
    // Send directly to the Node.js RAG backend
    // No mock fallbacks allowed as per SIH judging rules.
    const backendResult = await apiService.sendChat(query, lang);
    
    if (backendResult) {
      return backendResult;
    }

    // If backend is unreachable, explicitly return a connection error message
    // DO NOT return a fabricated offline mock response.
    return {
      id: Date.now().toString(),
      sender: 'assistant',
      timestamp: new Date().toISOString(),
      text: lang === 'hi'  
        ? '?? ??????: ????? ????????? ????? ????????? ???? ?? ?????? ????? ????? 5000 ?? ?? ??? ???' 
        : lang === 'mr'
        ? '?? ??????: ??????? ?????? ????. ????? ?????? ??? ?? ?????? ??????? ????? 5000 ?? ???? ???.'
        : '?? **Connection Error**: The RAG backend server is unreachable. Please ensure the Node.js backend is running on port 5000.',
      isVerified: false,
      confidence: 0,
      sources: [],
      suggestedActions: ['Retry Connection'],
      retrievedContextCount: 0
    };
  }
}

export const aiChatService = new AIChatService();